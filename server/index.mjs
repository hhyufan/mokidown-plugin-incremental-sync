import { createPluginServer } from './runtime/server.mjs';
import { openLegacyStorage } from './runtime/legacy.mjs';
import { join } from 'node:path';
import { homedir } from 'node:os';
import { readFileSync } from 'node:fs';
const directory = process.env.DATA_DIR || join(homedir(), '.mokidown-sync/data');
const token = process.env.SYNC_TOKEN || readFileSync(join(homedir(), '.mokidown-sync/token'), 'utf8').trim();
const storage = await openLegacyStorage(directory);
const server = createPluginServer({ plugins:['cloud-sync'],accessKeys:[{key:token,namespace:'default'}],instanceId:'mokidown-sync-local',basePath:'',corsOrigins:['tauri://localhost','http://tauri.localhost','https://tauri.localhost'] },storage);
server.listen(Number(process.env.PORT || 4319),process.env.HOST || '127.0.0.1',()=>console.log('Protocol v3 sync server ready'));
for(const signal of ['SIGINT','SIGTERM'])process.on(signal,()=>server.close(async()=>{await storage.close();process.exit(0);}));
